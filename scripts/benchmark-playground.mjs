import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const output = new URL("../output/playwright/", import.meta.url);

// Serialized into a playwright-cli run-code file. Its only inputs are the page and fixture data.
async function browserAcceptance(page, cases) {
  const requests = [];
  const consoleErrors = [];
  const onRequest = (request) => requests.push({ method: request.method(), url: request.url() });
  const onConsole = (message) => { if (message.type() === "error") consoleErrors.push(message.text()); };
  page.context().on("request", onRequest);
  page.on("console", onConsole);
  const navigation = Date.now();
  await page.reload();
  await page.waitForFunction(() => document.querySelector("#compile")?.disabled === false
    || document.querySelector("#status")?.textContent.includes("失败"), null, { timeout: 120000 });
  if (await page.locator("#compile").isDisabled()) throw new Error(await page.locator("#output").textContent());
  const initializationMs = Date.now() - navigation;
  const initializationText = await page.locator("#init-time").textContent();
  await page.evaluate(async () => {
    const compiler = await window.__mcfppCompilerRuntime.compiler;
    const original = compiler.compile.bind(compiler);
    window.__teavmMeasurement = null;
    compiler.compile = async (...args) => {
      const started = performance.now();
      const result = await original(...args);
      window.__teavmMeasurement = { result, wallMs: performance.now() - started, timings: compiler.lastTimings };
      return result;
    };
  });
  const results = [];
  let fileSwitch;
  for (const item of cases) {
    await page.getByRole("textbox", { name: "main.mcfpp 源代码", exact: true }).fill(item.source);
    await page.evaluate(() => { window.__teavmMeasurement = null; });
    const started = Date.now();
    await page.locator("#compile").click();
    await page.waitForFunction(() => window.__teavmMeasurement !== null, null, { timeout: 65000 });
    await page.waitForFunction(() => document.querySelector("#compile")?.disabled === false, null, { timeout: 65000 });
    const data = await page.evaluate(() => ({
      ...window.__teavmMeasurement,
      status: document.querySelector("#status")?.textContent,
      output: document.querySelector("#output")?.textContent,
      color: getComputedStyle(document.querySelector("#output")).color,
      run: document.querySelector("#run-output")?.textContent,
      runState: document.querySelector("#run-output")?.getAttribute("data-state"),
      selectorDisabled: document.querySelector("#files")?.disabled,
    }));
    results.push({ name: item.name, source: item.source, uiMs: Date.now() - started, ...data });
    if (item.name === "cold" && data.result.success) {
      const greet = data.result.files.find((file) => file.path.endsWith("/greet.mcfunction"));
      const main = data.result.files.find((file) => file.path.endsWith("/main.mcfunction"));
      await page.locator("#files").selectOption(greet.path);
      const greetText = await page.locator("#output").textContent();
      await page.locator("#files").selectOption(main.path);
      fileSwitch = { greet: greetText, main: await page.locator("#output").textContent() };
    }
    if (item.name === "error") await page.screenshot({ path: "output/playwright/teavm-error.png", fullPage: true });
  }
  await page.getByRole("textbox", { name: "main.mcfpp 源代码", exact: true }).evaluate((editor) => {
    editor.scrollLeft = 0;
    editor.dispatchEvent(new Event("scroll"));
  });
  await page.screenshot({ path: "output/playwright/teavm-success.png", fullPage: true });
  page.context().off("request", onRequest);
  page.off("console", onConsole);
  return { initializationMs, initializationText, fileSwitch, results, requests, consoleErrors };
}

await mkdir(output, { recursive: true });
if (process.argv[2] === "--compare") {
  const text = await readFile(resolve(process.argv[3]), "utf8");
  const match = /### Result\r?\n([^\r\n]+)/.exec(text);
  assert(match, "playwright-cli did not return a result");
  const browser = JSON.parse(match[1]);
  const native = JSON.parse(await readFile(new URL("../../MCFPP/browser/build/reports/browser/native-results.json", import.meta.url), "utf8"));
  assert.equal(browser.results.length, native.length);
  const files = (result) => [...result.files].sort((a, b) => a.path.localeCompare(b.path));
  for (let i = 0; i < native.length; i++) {
    const actual = browser.results[i], expected = native[i];
    assert.equal(actual.name, expected.name);
    assert.equal(actual.source, expected.source);
    assert.equal(actual.result.success, expected.result.success, `${actual.name}: success`);
    assert.deepEqual(files(actual.result), files(expected.result), `${actual.name}: generated bytes`);
    assert.equal(actual.result.loadedLibraries, 1);
    assert(actual.wallMs < 10000, `${actual.name}: compilation exceeded 10 seconds`);
    if (!actual.result.success) {
      assert.equal(actual.selectorDisabled, true);
      assert(actual.result.diagnostics.some((item) => item.severity === "error"));
      assert.equal(actual.color, "rgb(184, 39, 44)");
      assert(!actual.run.includes("Hello, MCFPP!"));
      if (actual.name === "custom-mni") assert(actual.output.includes("Custom MNI declarations are unavailable"));
    }
  }
  assert(browser.fileSwitch.greet.includes("Hello, MCFPP!"));
  assert(browser.fileSwitch.main.includes("Hello, MCFPP!"));
  assert.equal(browser.fileSwitch.main.trim().split("\n").length, 2, "default example should contain only two output commands");
  for (const name of ["cold", "warm", "recovered", "final-default"]) {
    const result = browser.results.find((item) => item.name === name);
    assert(result.run.includes("Hello, MCFPP!"), `${name}: DSB output missing`);
    assert(result.run.trim().endsWith("3"));
  }
  assert(browser.results.find((item) => item.name === "modified").run.trim().endsWith("4"));
  const runtimeOutput = browser.results.find((item) => item.name === "runtime-output").run.trim();
  const expectedRuntimeOutput = "3\n0\nchanged\n2\n1";
  const limitations = [];
  if (runtimeOutput !== expectedRuntimeOutput) {
    // SDK 0.2.2 reports 1 for `data get` on this three-element list. Keep this
    // observed simulator failure explicit; compiler output must still match JVM.
    assert.equal(runtimeOutput, "1\n0\nchanged\n2\n1", "unexpected runtime output regression");
    limitations.push({ name: "DSB runtime list size", expected: expectedRuntimeOutput, actual: runtimeOutput });
  }
  assert.equal(browser.results.find((item) => item.name === "shadowed-print").run.trim(), "12");
  assert(browser.requests.every((request) => request.method === "GET"));
  assert(!browser.requests.some((request) => /cjrtnc|leaningtech|\.jar(?:\?|$)/.test(request.url)));
  assert.deepEqual(browser.consoleErrors, []);
  await writeFile(new URL("teavm-browser-results.json", output), JSON.stringify({ ...browser, limitations }, null, 2) + "\n");
  console.log(`PASS: ${native.length} browser/native results match byte-for-byte; default DSB output, diagnostics, file switching and local-only compilation verified.`);
  for (const limitation of limitations) console.log(`KNOWN FAILURE: ${JSON.stringify(limitation)}`);
  console.log(JSON.stringify({ initializationMs: browser.initializationMs,
    cases: browser.results.map(({ name, wallMs, uiMs }) => ({ name, wallMs, uiMs })) }, null, 2));
} else {
  const cases = JSON.parse(await readFile(new URL("../../MCFPP/browser/benchmarks/cases.json", import.meta.url), "utf8"));
  await writeFile(new URL("teavm-acceptance.cjs", output),
    `async (page) => await (${browserAcceptance.toString()})(page, ${JSON.stringify(cases)})\n`);
  console.log("Prepared output/playwright/teavm-acceptance.cjs for playwright-cli run-code --filename.");
}
